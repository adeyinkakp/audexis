fn rgb(hex: u32) -> Color {
    Color::from_rgb((hex >> 16) as u8, (hex >> 8) as u8, hex as u8)
}

fn translucent(hex: u32, opacity: f32) -> Color {
    Color::from_af32rgb(opacity, (hex >> 16) as u8, (hex >> 8) as u8, hex as u8)
}

